#!/usr/bin/env python3
"""Dev-time importer: upstream theme checkout -> compact assets + generated header.
Not shipped. Needs Python 3.11+ and Pillow.

  python import_themes.py <upstream_dir> <out_dir> 
         [--bg-width 1920] [--bg-quality 60] [--thumb-width 480] [--max-bg 3] [--no-bg]

Expects <upstream_dir>/themes/<name>/{colors.toml,preview.png,backgrounds/*}.
"""
import sys, os, re, shutil, tomllib
from PIL import Image

KEYS = ["background","dark_background","darker_background","lighter_background",
        "foreground","dark_foreground","light_foreground","bright_foreground",
        "accent","selection","muted",
        "red","yellow","orange","green","cyan","blue","magenta","brown",
        "bright_red","bright_yellow","bright_green","bright_cyan","bright_blue","bright_magenta"]

def hexc(s):  # "#rrggbb" -> COLORREF 0x00BBGGRR
    s = s.lstrip('#'); return int(s[4:6] + s[2:4] + s[0:2], 16)

def main():
    args = sys.argv[1:]; pos = []; opt = {}; i = 0
    while i < len(args):
        if args[i].startswith('--'):
            k = args[i][2:]
            if i + 1 < len(args) and not args[i+1].startswith('--'): opt[k] = args[i+1]; i += 2
            else: opt[k] = '1'; i += 1
        else: pos.append(args[i]); i += 1
    src, out = pos[0], pos[1]
    bgw = int(opt.get('bg-width', 1920)); bgq = int(opt.get('bg-quality', 60))
    thw = int(opt.get('thumb-width', 480)); maxbg = int(opt.get('max-bg', 3)); nobg = 'no-bg' in opt
    themes = sorted(d for d in os.listdir(f"{src}/themes") if os.path.exists(f"{src}/themes/{d}/colors.toml"))
    shutil.rmtree(f"{out}/themes", ignore_errors=True); os.makedirs(f"{out}/themes")
    rows = []; total = 0
    for t in themes:
        c = tomllib.load(open(f"{src}/themes/{t}/colors.toml", "rb"))
        vals = []
        for k in KEYS:
            v = c.get(k)
            if v is None:  # light themes omit some; fall back
                v = c.get({"orange": "yellow", "brown": "red"}.get(k, "foreground"))
            vals.append(hexc(v))
        d = f"{out}/themes/{t}"; os.makedirs(d)
        p = f"{src}/themes/{t}/preview.png"
        if os.path.exists(p):
            im = Image.open(p).convert("RGB"); im.thumbnail((thw, thw*9//16 + 1), Image.LANCZOS)
            im.save(f"{d}/p.jpg", quality=70, optimize=True)
        nbg = 0
        bgdir = f"{src}/themes/{t}/backgrounds"
        if not nobg and os.path.isdir(bgdir):
            for f in sorted(os.listdir(bgdir))[:maxbg]:
                try: im = Image.open(f"{bgdir}/{f}").convert("RGB")
                except Exception as e: print("skip", t, f, e); continue
                im.thumbnail((bgw, bgw), Image.LANCZOS)
                im.save(f"{d}/b{nbg}.jpg", quality=bgq, optimize=True); nbg += 1
        sz = sum(os.path.getsize(f"{d}/{f}") for f in os.listdir(d)); total += sz
        rows.append((t, c.get("mode", "dark"), vals, nbg))
        print(f"{t:18} {sz//1024:6}K  bg={nbg}")
    h = ["// GENERATED by tools/import_themes.py - do not edit", "#pragma once",
         "namespace gen {", f"constexpr int kThemeCount = {len(rows)};", f"constexpr int kColorCount = {len(KEYS)};",
         "enum Color : unsigned char {" + ",".join("C_" + k.upper() for k in KEYS) + "};",
         "struct ThemeRow { const wchar_t* name; bool light; unsigned char bgCount; unsigned colors[kColorCount]; };",
         "constexpr ThemeRow kThemes[] = {"]
    for n, m, v, b in rows:
        h.append(f'  {{L"{n}", {"true" if m == "light" else "false"}, {b}, {{' + ",".join(f"0x{x:06X}" for x in v) + "}},")
    h += ["};", "}"]
    open(f"{out}/../src/themes.gen.h", "w").write("\n".join(h) + "\n")
    print(f"total assets {total//1024}K, {len(rows)} themes")
main()
